/** Las banderas sin lista propia tiran de la española, la del país donde arranca el juego. */
const FALLBACK = NAMES_BY_FLAG.ESP as NamePool;

/**
 * Un nombre de una bandera concreta. Gasta siempre **dos tiradas** del
 * generador, tenga la lista el tamaño que tenga: así ampliar las listas no mueve
 * nada de lo que se genere después con el mismo generador.
 */
export function randomNameFor(flag: string, rng: Rng): { firstName: string; lastName: string } {
  const pool = NAMES_BY_FLAG[flag] ?? FALLBACK;
  const first = Math.floor(rng.next() * pool.first.length);
  const last = Math.floor(rng.next() * pool.last.length);
  return {
    firstName: pool.first[first] as string,
    lastName: pool.last[last] as string
  };
}

/** Un nombre de la lista de casa, para quien no tiene bandera. */
export function randomName(rng: Rng): { firstName: string; lastName: string } {
  return randomNameFor('ESP', rng);
}
